"""Checks the split of the flight on the Weapons page: Split / Rejoin per attack section, LEAD / ELEMENT shown, the element born as the mirror of the
lead, the white drawing of the other attack, the deconfliction card (spacing at the split point; amber when only the timing clears it, red when an attack
parameter can), the red sliders, Apply by the seat, the state, Edit points steady. Usage: python3 tools/wpgroups-test.py [dtc.ini]
(default: the Bear Trap DTC of tests/fixtures)."""
import subprocess, sys, time, os
from playwright.sync_api import sync_playwright
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DTC = sys.argv[1] if len(sys.argv) > 1 else R + '/tests/fixtures/beartrap/Evil19_2_.ini'
srv = subprocess.Popen([sys.executable, R + '/tools/serve.py', '8784', '--directory', R], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL); time.sleep(1)
ok = True
def check(n, c):
    global ok; ok &= bool(c); print('OK  ' if c else 'FAIL', n)
try:
    ini = open(DTC, encoding='latin1').read()
    with sync_playwright() as p:
        br = p.chromium.launch(); errs = []
        pg = br.new_page(viewport={'width': 1500, 'height': 1000}, reduced_motion='reduce')
        pg.on('pageerror', lambda e: errs.append(str(e))); pg.on('dialog', lambda d: d.accept())
        pg.goto('http://localhost:8784/app/index.html'); pg.wait_for_timeout(800)
        pg.click('[data-t=wp]'); pg.evaluate("t=>__app.parse(t)", ini); pg.wait_for_timeout(1500)
        pg.click('[data-t=dtc]'); pg.click('[data-t=wp]'); pg.wait_for_timeout(800)
        sb = lambda: pg.locator('[data-split]').inner_text()
        who = lambda: pg.locator('.wshow [data-who].on').get_attribute('data-who') if pg.locator('.wshow').count() else None
        dive = lambda: pg.locator('input[data-sl=diveAngle]').input_value()
        setdive = lambda v: pg.locator('input[data-sl=diveAngle]').evaluate("(e,v)=>{e.value=v;e.dispatchEvent(new Event('input'))}", v)
        dc = lambda: pg.evaluate("()=>__app.wpPage._dc()")
        card = lambda: pg.locator('#wpr .wdc')
        check('one attack for the flight: Split, nothing to show, Apply has no group', sb() == 'Split' and who() is None and pg.inner_text('#wpapply').strip() == 'Apply to the DTC' and dc()['ghost'] is None)
        d0 = dive()
        # the page is drawn anew on Split: Edit points keeps its label (no On / Off flicker while the map goes home and back)
        pg.evaluate("()=>{window.EDL=[];new MutationObserver(l=>l.forEach(m=>{const e=document.querySelector('#wpmc [data-edit]');if(e)EDL.push(e.textContent)})).observe(document.body,{subtree:true,childList:true,characterData:true})}")
        pg.click('[data-split]'); pg.wait_for_timeout(500)
        check('Edit points does not flicker when the page is drawn anew', all(t == 'Edit points: Off' for t in pg.evaluate("()=>EDL")))
        check('Split: Rejoin, LEAD 1-2 shown with the attack of the flight, Apply names the lead', sb() == 'Rejoin' and who() == 'lead' and dive() == d0 and pg.inner_text('#wpapply').strip() == 'Apply to the DTC (lead)')
        check('the element is drawn white under the lead at once (the mirror)', dc()['ghost'] and [k for k, _ in dc()['ghost']][:2] == ['ingress', 'climb'])
        setdive('30'); pg.wait_for_timeout(300)
        pg.click('.wshow [data-who=elem]'); pg.wait_for_timeout(500)
        sd = pg.evaluate("()=>__app.wpPage._dc().sides")
        check('Type 2 mirror: the two leave the same VRP', sd and ((sd[0][0]['n'] - sd[1][0]['n']) ** 2 + (sd[0][0]['e'] - sd[1][0]['e']) ** 2) ** 0.5 < 300)
        check('ELEMENT 3-4: the mirror of the lead (its dive, the turn on the other side), Mirror on', who() == 'elem' and dive() == '30' and 'on' in pg.get_attribute('[data-mir]', 'class') and pg.locator('.wpl [data-set=side][data-v=left].on').count() == 1)
        pg.wait_for_timeout(900)
        g = dc()
        check('the mirror without fragments: flown together they meet over the target, a spacing keeps them apart: amber, no red sliders', g['dc']['met'] and not g['dc']['close'] and g['dc']['spacing'] > 0 and 'warn' in card().get_attribute('class') and pg.locator('.wpl .slr.dcl').count() == 0)
        # the element head on to the lead along its attack line: they would meet, a longer spacing keeps them apart (amber, no red sliders)
        pg.click('.wpl [data-set=side][data-v=right]'); pg.wait_for_timeout(300)
        check('a control of its own ends the mirror', 'on' not in pg.get_attribute('[data-mir]', 'class'))
        lh = pg.evaluate("()=>{const s=__app.wpPage.state();return s.fls.p.heading}")
        pg.locator('input[data-slnum=heading]').evaluate("(e,v)=>{e.value=v;e.dispatchEvent(new Event('change'))}", (lh + 180 - 1) % 360 + 1); pg.wait_for_timeout(1500)
        g = dc()
        check('head on: the timing keeps them apart (a spacing, amber, no red sliders)', g['dc']['met'] and not g['dc']['close'] and g['dc']['spacing'] > 0 and 'warn' in card().get_attribute('class') and pg.locator('.wpl .slr.dcl').count() == 0)
        # a bomb: the spacing keeps the two apart, the fragments are met whatever the attack: amber, no red sliders
        # (each attack has its own bomb: both get one)
        pg.select_option('select[data-pick=bomb]', '500'); pg.wait_for_timeout(300)
        pg.click('.wshow [data-who=lead]'); pg.wait_for_timeout(400)
        pg.select_option('select[data-pick=bomb]', '500'); pg.wait_for_timeout(300)
        pg.click('.wshow [data-who=elem]'); pg.wait_for_timeout(1300)
        g = dc()
        t = card().inner_text().upper()
        check('with the fragments: the spacing at the VRP, amber, no red sliders', g['dc']['spacing'] >= 25 and not g['dc']['close'] and 'warn' in card().get_attribute('class') and 'AT THE VRP' in t and pg.locator('.wpl .slr.dcl').count() == 0)
        # the shared egress: the element's egress controls locked, the card says the rejoin is visual
        pg.click('[data-egr=shared]'); pg.wait_for_timeout(700)
        lk = pg.evaluate("()=>[...document.querySelectorAll('[data-egcard] button,[data-egcard] input')].filter(e=>!e.closest('.wegsh')&&!e.closest('.nst')).every(e=>e.disabled)")
        check('Shared egress: the element\'s egress controls are locked, the card says the rejoin is visual', lk and 'SHARED EGRESS' in card().inner_text().upper() and pg.locator('[data-ealt]').count() == 2)
        pg.click('.wshow [data-who=lead]'); pg.wait_for_timeout(400)
        pg.click('[data-set=oa2Mode][data-v=egress]'); pg.wait_for_timeout(400)
        pg.click('.wshow [data-who=elem]'); pg.wait_for_timeout(500)
        g = dc(); eg = [z for z in g['ghost'] if z[0] == 'egress']
        check('Shared egress: the element\'s OA2 is the lead\'s egress point %s %s' % (g['oa2'], eg and eg[-1][1][-1]), g['oa2'] and eg and abs(g['oa2'][0] - eg[-1][1][-1][0]) < 100 and abs(g['oa2'][1] - eg[-1][1][-1][1]) < 100)
        pg.click('[data-ealt="1"]'); pg.wait_for_timeout(500)
        check('+1 000 ft: said on the card', '1 000 FT HIGHER' in card().inner_text().upper())
        pg.click('[data-egr=own]'); pg.wait_for_timeout(500)
        check('Own egress again: the controls are free', pg.evaluate("()=>[...document.querySelectorAll('[data-egcard] button')].filter(e=>!e.closest('.wegsh')).some(e=>!e.disabled)"))
        s = pg.evaluate("()=>{const s=__app.wpPage.state();return {split:s.grp.popup.split,who:s.grp.popup.who,inMode:s.inMode}}")
        check('the state keeps the split for the mission file', s == {'split': True, 'who': 'elem', 'inMode': 'popup'})
        pg.click('[data-mode=hadb]'); pg.wait_for_timeout(500)
        check('HADB has its own split', sb() == 'Split')
        pg.click('[data-split]'); pg.wait_for_timeout(600)
        sd = pg.evaluate("()=>__app.wpPage._dc().sides")
        check('HADB mirror: the two leave the same line-up point', sd and ((sd[0][0]['n'] - sd[1][0]['n']) ** 2 + (sd[0][0]['e'] - sd[1][0]['e']) ** 2) ** 0.5 < 300)
        pg.click('[data-split]'); pg.wait_for_timeout(400)
        pg.click('[data-mode=toss]'); pg.wait_for_timeout(500)
        check('TOSS without angle off: no split (flown in formation)', pg.is_disabled('[data-split]'))
        pg.click('[data-mode=popup]'); pg.wait_for_timeout(500)
        check('the pop-up comes back on the element', who() == 'elem')
        pg.click('[data-split]'); pg.wait_for_timeout(500)
        check('Rejoin: one attack again, the lead\'s', sb() == 'Split' and who() is None and dive() == '30' and dc()['ghost'] is None and card().count() == 0)
        check('no page errors', not errs)
        if errs: print(errs)
finally:
    srv.terminate()
print('ALL OK' if ok else 'SOME FAILED'); sys.exit(0 if ok else 1)
