// Builds app/js/data/basemap.js (offline coast + borders for the map tab) from Natural Earth via the npm
// packages world-atlas (ISC, data public domain) and topojson-client (ISC).
// Rivers and lakes: Natural Earth 10m (public domain) ne_10m_rivers_lake_centerlines_scale_rank.geojson and ne_10m_lakes.geojson (github.com/nvkelso/natural-earth-vector, folder geojson).
// Usage: node tools/make-basemap.mjs <dir with node_modules containing world-atlas and topojson-client> [dir with the two Natural Earth geojson files]
import fs from 'fs'; import path from 'path'; import {createRequire} from 'module';
const req = createRequire(path.resolve(process.argv[2] || '.') + '/');
const tj = req('topojson-client'), rd = f => JSON.parse(fs.readFileSync(path.dirname(req.resolve('world-atlas/package.json')) + '/' + f, 'utf8')),
  land = rd('land-10m.json'), ctr = rd('countries-10m.json');
const B = [105, 22, 150, 52]; // lon0 lat0 lon1 lat1
const r = v => Math.round(v * 1000) / 1000;
// Sutherland-Hodgman against the box
function clipPoly(ring) {
  const edges = [[0, B[0], 1], [0, B[2], -1], [1, B[1], 1], [1, B[3], -1]];
  let p = ring;
  for (const [ax, v, s] of edges) {
    const out = [], inside = q => s * (q[ax] - v) >= 0;
    for (let i = 0; i < p.length; i++) {
      const a = p[i], b = p[(i + 1) % p.length], ia = inside(a), ib = inside(b);
      if (ia) out.push(a);
      if (ia != ib) { const t = (v - a[ax]) / (b[ax] - a[ax]), o = [0, 0]; o[ax] = v; o[1 - ax] = a[1 - ax] + t * (b[1 - ax] - a[1 - ax]); out.push(o); }
    }
    p = out; if (!p.length) break;
  }
  return p;
}
const inb = q => q[0] >= B[0] && q[0] <= B[2] && q[1] >= B[1] && q[1] <= B[3];
function clipLine(l) { const out = []; let cur = []; for (const q of l) { if (inb(q)) cur.push(q); else { if (cur.length > 1) out.push(cur); cur = []; } } if (cur.length > 1) out.push(cur); return out; }
const polys = [];
const lf = tj.feature(land, land.objects.land);
for (const g of lf.features) for (const poly of (g.geometry.type == 'Polygon' ? [g.geometry.coordinates] : g.geometry.coordinates)) {
  const ring = clipPoly(poly[0]); if (ring.length > 2) polys.push(ring.map(q => [r(q[0]), r(q[1])]));
}
const mesh = tj.mesh(ctr, ctr.objects.countries, (a, b) => a !== b);
const lines = []; for (const l of mesh.coordinates) for (const c of clipLine(l)) lines.push(c.map(q => [r(q[0]), r(q[1])]));
// rivers and lakes (optional second argument)
let rivers = [], lakes = [];
if (process.argv[3]) {
  const gj = f => JSON.parse(fs.readFileSync(path.resolve(process.argv[3], f), 'utf8'));
  for (const f of gj('ne_10m_rivers_lake_centerlines_scale_rank.geojson').features) { const g = f.geometry; if (!g) continue; for (const l of (g.type == 'LineString' ? [g.coordinates] : g.coordinates)) for (const c of clipLine(l)) rivers.push(c.map(q => [r(q[0]), r(q[1])])); }
  for (const f of gj('ne_10m_lakes.geojson').features) { const g = f.geometry; if (!g) continue; for (const poly of (g.type == 'Polygon' ? [g.coordinates] : g.coordinates)) { const ring = clipPoly(poly[0]); if (ring.length > 2) lakes.push(ring.map(q => [r(q[0]), r(q[1])])); } }
} else { const old = fs.existsSync('app/js/data/basemap.js') ? fs.readFileSync('app/js/data/basemap.js', 'utf8') : ''; const m = old.match(/export default (.*);\n$/s); if (m) { const o = JSON.parse(m[1]); rivers = o.rivers || []; lakes = o.lakes || []; } }
fs.writeFileSync('app/js/data/basemap.js', '// Generated by tools/make-basemap.mjs. Natural Earth (public domain) via world-atlas, plus the Natural Earth 10m rivers and lakes. [lon,lat] rings: land polygons, country borders, rivers, lakes.\nexport default ' + JSON.stringify({land: polys, borders: lines, rivers, lakes}) + ';\n');
console.log(polys.length, 'land rings,', lines.length, 'border lines,', rivers.length, 'river lines,', lakes.length, 'lakes');
